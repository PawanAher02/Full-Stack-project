-- 1. Create the table explicitly in the 'public' schema
CREATE TABLE IF NOT EXISTS public.enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    name TEXT NOT NULL,
    mobile TEXT NOT NULL,
    email TEXT,
    course TEXT NOT NULL,
    timing TEXT,
    message TEXT
);

-- 2. Grant table and schema permissions to anon and authenticated roles
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON TABLE public.enquiries TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;

-- 4. Policies for public insert and admin select
DROP POLICY IF EXISTS "Allow public visitors to submit enquiries" ON public.enquiries;
CREATE POLICY "Allow public visitors to submit enquiries"
ON public.enquiries
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow authenticated admins to read enquiries" ON public.enquiries;
CREATE POLICY "Allow authenticated admins to read enquiries"
ON public.enquiries
FOR SELECT
TO authenticated
USING (true);

-- 5. Force Supabase PostgREST API to instantly refresh its schema cache
NOTIFY pgrst, 'reload schema';
